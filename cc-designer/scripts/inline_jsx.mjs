#!/usr/bin/env node
// 把 `<script type="text/babel" src="x.jsx">` 內嵌進 HTML，產生可雙擊開啟的交付檔。
// Babel 以 XHR 讀外部 JSX，瀏覽器在 file:// 會擋下這個請求，畫面只剩空白。
//
// 用法：node inline_jsx.mjs <source.html> <output.html> [--force]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';

const GENERATED_MARK = '<!-- generated by inline_jsx.mjs; edit the source HTML and JSX, then rebuild -->';
const SCRIPT_WITH_SRC = /<script\b([^>]*?)\bsrc=(["'])([^"']+)\2([^>]*)>\s*<\/script>/gi;
const BABEL_TYPE = /\btype=(["'])text\/babel\1/i;
const HAS_SCHEME = /^([a-z][a-z0-9+.-]*:|\/\/)/i;

function stop(code, message) {
  console.log(JSON.stringify({ status: 'FAIL', code, message }, null, 2));
  process.exit(1);
}

function resolveJsx(projectRoot, src) {
  if (HAS_SCHEME.test(src)) stop('remote_jsx', `只能內嵌本地 JSX：${src}`);
  const file = resolve(projectRoot, src);
  const fromRoot = relative(projectRoot, file);
  if (fromRoot.startsWith('..') || isAbsolute(fromRoot)) stop('jsx_outside_project', `JSX 不在專案資料夾內：${src}`);
  if (!existsSync(file)) stop('jsx_missing', `找不到 JSX：${src}`);
  return { file, label: fromRoot.split(sep).join('/') };
}

function inlineBabelScripts(html, projectRoot) {
  const inlined = [];
  const output = html.replace(SCRIPT_WITH_SRC, (tag, before, _quote, src, after) => {
    if (!BABEL_TYPE.test(before + after)) return tag;
    const { file, label } = resolveJsx(projectRoot, src);
    inlined.push(label);
    // 原樣保留 `</script` 會提早結束這個標籤，後面的 JSX 變成頁面文字。
    const code = readFileSync(file, 'utf8').replace(/<\/script/gi, '<\\/script');
    return `<script type="text/babel" data-source="${label}">\n${code}\n</script>`;
  });
  return { output, inlined };
}

function main(argv) {
  const positional = argv.filter((arg) => !arg.startsWith('--'));
  const force = argv.includes('--force');
  if (positional.length !== 2) stop('usage', 'node inline_jsx.mjs <source.html> <output.html> [--force]');

  const [source, output] = positional.map((path) => resolve(path));
  if (source === output) stop('source_is_output', '輸出檔不可與來源相同，否則下次無法重建。');
  if (!existsSync(source)) stop('source_missing', `找不到來源 HTML：${source}`);
  if (existsSync(output) && !force && !readFileSync(output, 'utf8').includes(GENERATED_MARK)) {
    stop('refuse_overwrite', `輸出檔不是本工具產生的，加 --force 才覆蓋：${output}`);
  }

  const { output: html, inlined } = inlineBabelScripts(readFileSync(source, 'utf8'), dirname(source));
  writeFileSync(output, `${html.trimEnd()}\n${GENERATED_MARK}\n`, 'utf8');
  console.log(JSON.stringify({ status: 'PASS', output, inlined }, null, 2));
}

main(process.argv.slice(2));
